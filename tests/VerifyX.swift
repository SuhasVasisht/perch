                widget?.panel.close()
                preferences.removePersistentDomain(forName: suiteName)
                exit(1)
            }
        }
    }

    private func check(_ name: String, _ passed: Bool) throws {
        let safety = OffscreenHost.safetyFailures()
        guard safety.isEmpty else { throw VerificationFailure(message: "Nonactivating host safety: \(safety.joined(separator: ", "))") }
        guard passed else { throw VerificationFailure(message: name) }
        checks += 1
        print("PASS \(name)")
        fflush(stdout)
    }

    @discardableResult private func js(_ expression: String) async throws -> Any? {
        try await widget.webView!.evaluateJavaScript(expression)
    }

    private func number(_ expression: String) async throws -> Double {
        guard let value = try await js(expression) as? NSNumber else {
            throw VerificationFailure(message: "Expected a number for \(expression)")
        }
        return value.doubleValue
    }

    private func yes(_ expression: String) async throws -> Bool {
        try await js(expression) as? Bool == true
    }

    private func pause(_ seconds: Double = 0.8) async throws {
        try await Task.sleep(nanoseconds: UInt64(seconds * 1_000_000_000))
    }

    private func wait(_ expression: String) async throws {
        for _ in 0..<200 {
            if (try? await yes(expression)) == true { return }
            try await pause(0.05)
        }
        throw VerificationFailure(message: "Timed out: \(expression)")
    }

